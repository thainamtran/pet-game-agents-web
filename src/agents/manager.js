import { writeText } from "../files.js";

export function managerNode(state) {
  const playable = Boolean(state.playable);
  const retries = Number(state.retries || 0);
  const maxRetries = Number(state.maxRetries || 3);
  const report = state.testReport || {};

  if (playable) {
    writeOutputReadme(state, true);
    return { status: "playable", log: ["manager: game is playable; stopping the loop"] };
  }
  if (retries >= maxRetries) {
    writeOutputReadme(state, false);
    const summary = report.summary || "unknown failure";
    return {
      status: "failed",
      log: [`manager: still not playable after ${retries} retry(ies); giving up (${summary})`],
    };
  }
  const category = state.failureCategory || report.category || "code";
  const target = category === "design" ? "designer" : "coder";
  return {
    status: "running",
    retries: retries + 1,
    log: [`manager: not playable (${category}); retry ${retries + 1}/${maxRetries} via ${target}`],
  };
}

export function routeAfterManager(state) {
  if (state.playable || state.status === "playable") return "done";
  if (state.status === "failed") return "done";
  const category = state.failureCategory || "code";
  if (category === "design") return "design";
  return "code";
}

function writeOutputReadme(state, success) {
  const design = state.design || {};
  const title = design.title || "Little Companion";
  const species = state.species || design.species || "pet";
  const theme = state.theme || design.theme || "";
  const name = design.petNameDefault || "Mochi";
  let body;
  if (success) {
    body = `# ${title}

A cozy pet-raising game (game nuôi thú) generated by the pet-game-agents-web pipeline.

- Species: ${species}
- Theme: ${theme}
- Default name: ${name}

Open the web app to play: feed, play, sleep, and keep the stats above zero.
`;
  } else {
    const report = state.testReport || {};
    body = `# Build did not finish

The manager stopped after reaching the retry limit. Last test summary:

${report.summary || "No report."}
`;
  }
  writeText(state.outputDir, "README.md", body);
}
